"""Writes gn/bdk/bdk_flags.gni from PlatformIO's compile_commands.json (an lwIP unit of env beken-bk7231n-nokey):
the include path and defines the CHIP code needs to see lwIP 2.2.0 (LibreTiny port), FreeRTOS and BDK headers
exactly as the firmware does. BLE, Wi-Fi MAC internals, BDK mbedTLS 2.6 and ESPurna/Arduino flags are left out."""
import json, shlex, sys
src, out = sys.argv[1], sys.argv[2]
d = json.load(open(src))
unit = next(e for e in d if e['file'].replace(chr(92), '/').endswith('library-lwip/src/core/ipv4/dhcp.c'))
args = shlex.split(unit['command'].replace(chr(92), '/'), posix=True)
skip_inc = ('ble_5_x_rw', '/ip/lmac', '/ip/umac', '/ip/mac', '/ip/ke', 'mbedtls', 'wpa_supplicant', 'espurna', 'libretiny-include', 'camera', 'video', 'jpeg', 'usb', 'spidma')
keep_def = ('CFG_', 'WIFI_BLE_COEXIST', 'INCLUDE_xTaskGetHandle', 'LT_BK', 'LT_HAS_FREERTOS', 'LT_HAS_LWIP', 'LIBRETINY=', 'MCU=', 'FAMILY=')
inc, defs = [], []
for a in args:
    if a.startswith('-I'):
        if not any(s in a for s in skip_inc) and a not in inc:
            inc.append(a)
    elif a.startswith('-D'):
        if a[2:].startswith(keep_def) and a not in defs:
            defs.append(a)
own = '-I' + '/mnt/c/working/ginhub/matter-bk7231n/gn/bdk'   # sys_config.h with CFG_SUPPORT_BLE=0 etc. (LT custom_options)
with open(out, 'w', newline='\n') as f:
    f.write('# generated by tools/gen_bdk_flags.py from PlatformIO compile_commands.json - do not edit\n')
    f.write('bdk_defines = [\n' + ''.join('  "%s",\n' % x for x in defs + ['-DCONFIG_IPV6=1']) + ']\n')
    f.write('bdk_include_flags = [\n' + ''.join('  "%s",\n' % x for x in [own] + inc) + ']\n')
print(len(inc), 'includes', len(defs), 'defines')
